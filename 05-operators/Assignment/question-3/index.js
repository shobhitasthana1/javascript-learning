// Increment example
let count = 5;

console.log("Initial value:", count);

count++;  // increment by 1

console.log("After count++:", count);


// Decrement example
let count2 = 5;

console.log("Initial value:", count2);

count2--;  // decrement by 1

console.log("After count--:", count2);
