// Create a variable city = “Bhopal”.
// If city is “Bhopal” → log “MP”
// Else if city is “Delhi” → log “Capital”
// Else → log “Unknown City”

// take input from user
let city = prompt("Enter your city");

// check city
if (city === "Bhopal") {
    console.log("MP");
}
else if (city === "Delhi") {
    console.log("Capital");
}
else {
    console.log("Unknown City");
}
