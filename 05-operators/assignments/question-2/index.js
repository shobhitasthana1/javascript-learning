
// Write: let x = 5; x = x + 3;
// Now rewrite the same using +=.
// Do the same for -=, *=, /=.


// Using normal assignment
let x = 5;
x = x + 3;
console.log("After x = x + 3 →", x);


// Using += operator
let a = 5;
a += 3;   // same as a = a + 3
console.log("After a += 3 →", a);


// Using -= operator
let b = 5;
b -= 3;   // same as b = b - 3
console.log("After b -= 3 →", b);


// Using *= operator
let c = 5;
c *= 3;   // same as c = c * 3
console.log("After c *= 3 →", c);


// Using /= operator
let d = 5;
d /= 3;   // same as d = d / 3
console.log("After d /= 3 →", d);




