// JavaScript Operators

// 1. Arithmetic Operators
let a = 10;
let b = 5;

console.log("Addition:", a + b);
console.log("Subtraction:", a - b);
console.log("Multiplication:", a * b);
console.log("Division:", a / b);
console.log("Modulus:", a % b);


// 2. Assignment Operator
let x = 10;
console.log("x:", x);

x += 5; // x = x + 5
console.log("x after += 5:", x);

x -= 2;
console.log("x after -= 2:", x);


// 3. Comparison Operators
let num1 = 10;
let num2 = "10";

console.log("num1 == num2:", num1 == num2);   // true
console.log("num1 === num2:", num1 === num2); // false
console.log("num1 != num2:", num1 != num2);
console.log("num1 > 5:", num1 > 5);


// 4. Logical Operators
let age = 20;

console.log(age > 18 && age < 30); // AND
console.log(age > 18 || age < 10); // OR
console.log(!(age > 18)); // NOT


// 5. Increment and Decrement
let count = 5;

count++;
console.log("After increment:", count);

count--;
console.log("After decrement:", count);


// 6. String Operator
let firstName = "Shobhit";
let lastName = "Asthana";

let fullName = firstName + " " + lastName;
console.log("Full Name:", fullName);


// done
console.log("Operators example completed");



